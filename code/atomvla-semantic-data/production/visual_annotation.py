"""Video-conditioned annotation with explicit evidence and full timeline accounting.
The VLM proposes silver labels. Structural validation is NOT semantic verification.
Unknown, idle and sustained holds are retained separately from primitive targets.
"""
import json,re
import numpy as np
from complete_annotation import EVENT_SCHEMAS,intervals
