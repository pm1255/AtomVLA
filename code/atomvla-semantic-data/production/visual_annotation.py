VERSION='atomvla_full_visual_v1'

def sample_rows(pose,grip,maximum=40):
 """Uniform context plus observed gripper/motion changes; no verb assumptions."""
 n=len(pose)
 if n<=maximum:return list(range(n))
 g=np.asarray(grip,float).reshape(n,-1);p=np.asarray(pose,float)
 span=np.maximum(np.ptp(g,axis=0),1e-6)
 change=np.max(abs(np.diff(g,axis=0))/span,axis=1)
 motion=np.linalg.norm(np.diff(p[...,:3],axis=0),axis=-1).max(axis=1)
 q=p[...,3:];q=q/np.maximum(np.linalg.norm(q,axis=-1,keepdims=True),1e-8)
 rot=2*np.arccos(np.clip(abs((q[1:]*q[:-1]).sum(-1)),0,1)).max(axis=1)
 score=change+np.minimum(motion/.02,1)*.15+np.minimum(rot/.2,1)*.15
 chosen=set(np.linspace(0,n-1,maximum//2,dtype=int).tolist())
 for i in np.argsort(-score,kind='stable'):
  if score[i]<.03:break
  if any(abs(int(i)-j)<2 for j in chosen):continue
  for j in (int(i),int(i)+1):
   if len(chosen)<maximum:chosen.add(j)
  if len(chosen)>=maximum:break
 for i in np.linspace(0,n-1,maximum,dtype=int):
  if len(chosen)>=maximum:break
  chosen.add(int(i))
 return sorted(chosen)

def prompt(n,arms,instruction,rows,pose,grip,source):
 measurements=[]
 for t in rows:
  measurements.append({'row':t,'xyz':np.asarray(pose[t,:,:3]).round(3).tolist(),'gripper':np.asarray(grip[t]).round(3).tolist()})
 return f'''Annotate the OBSERVED robot episode, not the intended instruction. Images are chronological, each labeled with exact source row and camera. Coordinate frame is source-native. Source={source}. Physical arms={arms}. There are {n} states, transitions [0,{n-1}). A segment [start,end) ends at observed state end. Adjacent segments share their boundary state. Cover every arm's full timeline with NON-OVERLAPPING segments. Group frames into a few meaningful operations; do NOT create one segment per sampled frame. Aim for 2-12 segments per arm if the episode supports it. Use compact JSON, no prose outside JSON. Output JSON only: {{"segments":[...]}}.
For a primitive segment use {{"kind":"primitive","verb":"...","start":0,"end":10,"arguments":{{"object":"visible_object_reference","target":"visible_target_reference","arm":"left","completion":"observed_condition"}},"events":[{{"role":"...","row":10}}],"observation":"specific visible evidence for object, operation and completion"}}.
For example, a free-space move is {{"kind":"primitive","verb":"move","start":0,"end":10,"arguments":{{"object":"gripper","target":"above_cup","arm":"left","completion":"arrived"}},"events":[{{"role":"arrived","row":10}}],"observation":"The empty gripper approaches the visible cup."}}. NEVER use "kind":"move".
All arguments are strings (English snake_case); never put coordinates/numbers in arguments. Arm must be left/right/both (single-arm maps to left). The only continuous target will be read from the measured endpoint pose, NEVER generated by you.
Allowed verbs and ordered variable event schemas: {json.dumps(EVENT_SCHEMAS)}.
Use move for visible free-space transport, approach for approach, open/close for articulated objects, NOT gripper aperture alone. pick requires acquisition/lift evidence, place requires supported release evidence; do not label every gripper closure as pick. Recognize observed push/pull/rotate/flip/insert/toggle/press/click/strike/handover when supported. Do not force the instruction's verb on the entire trajectory. move and approach use ONE final frame. pick can have 2 or 3 meaningful frames; other verbs use only visible necessary events from their schema. Every event row is strictly after start, increasing, last row equals end. All boundaries/events MUST be from sampled rows {rows}; do not invent unseen precision.
For non-manipulation or uncertain spans use {{"kind":"idle"|"hold"|"unresolved","start":0,"end":10,"arm":"left","observation":"visible evidence or exact uncertainty"}}. Hold includes maintaining a grasp/contact; never treat it as idle. If operation, object identity, success or boundaries cannot be determined, mark unresolved. Do not silently discard these spans. Stationary pose alone is insufficient proof of idle. Do not infer successful completion just because the trajectory ends. Never claim human verification. Handover with arm both must replace overlapping intervals for BOTH arms.
Instruction (context only): {json.dumps(instruction)}
Measured state rows (gripper sign/units source-native, infer open visually): {json.dumps(measurements)}'''

def parse_json(text):
 text=text.strip()
 if text.startswith('```'):
  text=re.sub(r'^```(?:json)?\s*','',text);text=re.sub(r'\s*```$','',text)
 obj=json.loads(text)
 if not isinstance(obj,dict) or not isinstance(obj.get('segments'),list):raise ValueError('expected segments array')
 return obj

def validate_prediction(doc,n,arms,rows,evidence):
 """Reject invalid intervals and both sides of overlaps; materialize all gaps."""
 if n<2:raise ValueError('episode has no transition')
 allowed=set(rows);valid=[];rejected=[]
 for i,raw in enumerate(doc['segments']):
  try:
   a=dict(raw);s,e=a['start'],a['end'];kind=a['kind']
   if type(s)is not int or type(e)is not int or not 0<=s<e<n:raise ValueError('bounds')
   if s not in allowed or e not in allowed:raise ValueError('unobserved boundary')
   arm=a['arguments']['arm'] if kind=='primitive' else a['arm']
   targets=arms if arm=='both' else [arm]
   if not targets or any(x not in arms for x in targets):raise ValueError('physical arm mismatch')
   if not isinstance(a.get('observation'),str) or len(a['observation'].strip())<8:raise ValueError('missing visual rationale')
   if kind=='primitive':
    a.update(quality='silver',evidence={**evidence,'observation':a['observation'],'semantic_verification':False},review_reasons=['model_annotation_not_independently_verified','sampled_frame_boundaries'])
    validate_annotation(a,n)
    if any(ev['row'] not in allowed for ev in a['events']):raise ValueError('unobserved event')
   elif kind not in ('idle','hold','unresolved'):raise ValueError('unknown segment kind')
   a['_arms']=list(targets);valid.append(a)
  except (ValueError,KeyError,TypeError) as exc:rejected.append({'index':i,'reason':str(exc),'prediction':raw})
 occupancy={arm:np.zeros(n-1,np.int32) for arm in arms}
 for a in valid:
  for arm in a['_arms']:occupancy[arm][a['start']:a['end']]+=1
 accepted=[]
 for a in valid:
  if any(np.any(occupancy[arm][a['start']:a['end']]>1) for arm in a['_arms']):
   rejected.append({'reason':'overlap_on_physical_arm','prediction':{k:v for k,v in a.items() if not k.startswith('_')}})
  else:accepted.append(a)
 covered={arm:np.zeros(n-1,bool) for arm in arms};resolved={arm:np.zeros(n-1,bool) for arm in arms}
 for a in accepted:
  for arm in a.pop('_arms'):
   covered[arm][a['start']:a['end']]=True
   if a['kind']!='unresolved':resolved[arm][a['start']:a['end']]=True
 for arm in arms:
  for gap in intervals(~covered[arm]):accepted.append({'kind':'unresolved','arm':arm,**gap,'observation':'No valid non-overlapping visual annotation for this interval.'})
 accepted.sort(key=lambda x:(x['start'],x['end'],x.get('arm',x.get('arguments',{}).get('arm',''))))
 counts={'total_arm_transitions':(n-1)*len(arms),'resolved_candidate_transitions':sum(int(x.sum()) for x in resolved.values()),'unresolved_transitions':sum(int((~x).sum()) for x in resolved.values())}
 return {'schema':VERSION,'segments':accepted,'annotations':[a for a in accepted if a['kind']=='primitive'],'rejected':rejected,'counts':counts,'full_timeline_accounted':True,'automatically_labeled_complete':counts['unresolved_transitions']==0,'verified_complete':False,'evidence':evidence}

def compact_prompt(n,arms,instruction,rows):
 return f'''Describe the observed robot actions in this chronological sequence. Each image is one timestep; its row number is printed above the camera views. Task context: {json.dumps(instruction)}. Physical arms: {arms}.
Return ONLY a JSON array of segments. Each segment is exactly:
[verb, arm, start_row, end_row, object, target, [[event_role, event_row], ...], visible_evidence]
Example: [["move","left",0,20,"gripper","above_cup",[["arrived",20]],"The empty gripper moves above the cup."]]
Use a few meaningful operations, NOT one segment per image. Cover the whole episode from row 0 to {n-1} for each arm, without overlaps. Use only these observed rows: {rows}. All object/target values are string descriptions. Never generate poses.
Allowed verbs and event-role sequences: {json.dumps(EVENT_SCHEMAS)}.
Events must be strictly after segment start and in chronological order; the last event is at segment end. move/approach have only an endpoint image. pick needs visible closure and lift; place needs visible release. open/close refer to doors/drawers, not the gripper. Do not invent events to match the instruction. When uncertain use verb "unresolved", object and target "unknown", events []; idle and hold also use events []. Never infer idle from stationary pose alone. Handover arm "both" covers both arms simultaneously. Output no markdown or explanations outside JSON.'''

def parse_compact(text):
 text=text.strip()
 if text.startswith('```'):
  text=re.sub(r'^```(?:json)?\s*','',text);text=re.sub(r'\s*```$','',text)
 data=json.loads(text)
 if not isinstance(data,list):raise ValueError('expected compact segment list')
 segments=[]
 for row in data:
  if not isinstance(row,list) or len(row)!=8:raise ValueError('expected eight fields per segment')
  verb,arm,start,end,obj,target,events,observation=row
  if verb in ('idle','hold','unresolved'):segments.append(dict(kind=verb,arm=arm,start=start,end=end,observation=observation));continue
  if verb not in EVENT_SCHEMAS:raise ValueError('unknown verb')
  if not isinstance(events,list) or any(not isinstance(e,list) or len(e)!=2 for e in events):raise ValueError('invalid event array')
  # Completion symbol is mechanically derived from the explicitly labeled event;
  # no object or event values are fabricated or repaired.
  completion=events[-1][0] if events else ''
  segments.append(dict(kind='primitive',verb=verb,start=start,end=end,arguments=dict(object=obj,target=target,arm=arm,completion=completion),events=[dict(role=k,row=v) for k,v in events],observation=observation))
 return {'segments':segments}
